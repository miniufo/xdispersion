# --------------------------------------------------------------------------- #
#  Module-scoped parametrised fixture                                         #
#                                                                             #
#  Builds RelativeDispersion with a *chunk* parameter so that the             #
#  chunked code paths (``_get_all_chunked`` for ragged, dask pair             #
#  chunking for non-ragged) are exercised.  Building blocks are NOT           #
#  .load()-ed — they are computed lazily inside cal_measures.                 #
#                                                                             #
#  The reference NC file (pre-generated by generate_ref.py) is also           #
#  loaded for golden-file comparison.                                         #
# --------------------------------------------------------------------------- #
@pytest.fixture(scope='module', params=['ragged', 'local', 'nonlocal'])
def ctx(request):
    if request.param == 'ragged':
        dset = xr.open_dataset('./data/glad32.nc')
        rd = RelativeDispersion(dset, xpos='longitude', ypos='latitude',
                                uvel='ve', vvel='vn', maxtlen=4 * 24 * 80,
                                time='time', Rearth=6371.2, ID='traj',
                                coord='latlon', ragged=True,
                                chunk=RAGGED_CHUNK)
        p_all = rd.get_all_pairs()
        pairs = rd.get_original_pairs(p_all, r0=[0.08, 0.18])
        assert len(pairs.pair) == 171
    elif request.param == 'local':
        dset = xr.open_dataset('./data/Particles_local.nc')
        rd = RelativeDispersion(dset, xpos='xpos', ypos='ypos',
                                uvel='uvel', vvel='vvel',
                                time='time', ID='ID',
                                coord='cartesian', ragged=False,
                                chunk=NONRAGGED_CHUNK)
        p_all = rd.get_all_pairs()
        pairs = rd.get_original_pairs(p_all, r0=[0, 0.01])
        assert len(pairs.pair) == 2920
    else:
        dset = xr.open_dataset('./data/Particles_nonlocal.nc')
        rd = RelativeDispersion(dset, xpos='xpos', ypos='ypos',
                                uvel='uvel', vvel='vvel',
                                time='time', ID='ID',
                                coord='cartesian', ragged=False,
                                chunk=NONRAGGED_CHUNK)
        p_all = rd.get_all_pairs()
        pairs = rd.get_original_pairs(p_all, r0=[0, 0.01])
        assert len(pairs.pair) == 2920

    ref_path = f'./data/ref_measures_{request.param}.nc'
    if not os.path.exists(ref_path):
        pytest.fail(
            f'Reference file {ref_path} not found.\n'
            f'Run  python tests/generate_ref.py  first to generate it.'
        )
    ref = xr.open_dataset(ref_path)

    # Compute all measures once (building blocks are computed inside
    # cal_measures, not .load()-ed in the fixture).
    measures = cal_measures(rd, pairs, rbins, one_by_one=True).load()

    return {
        'kind'   : request.param,
        'rd'     : rd,
        'pairs'  : pairs,
        'ref'    : ref,
        'measures': measures,
    }


# --------------------------------------------------------------------------- #
#  Helper for golden-file comparison                                          #
# --------------------------------------------------------------------------- #
def _assert_close(result_vals, ref_vals, rtol=2e-3, atol=1e-6):
    """Compare two arrays, ignoring positions where either is NaN/inf.

    ``atol`` handles near-zero values where chunked (dask) vs. in-memory
    (numpy) computation order produces tiny floating-point differences
    that inflate the *relative* error.
    """
    result_vals = np.asarray(result_vals, dtype=float)
    ref_vals    = np.asarray(ref_vals,    dtype=float)
    valid = np.isfinite(ref_vals) & np.isfinite(result_vals)
    if valid.any():
        np.testing.assert_allclose(
            result_vals[valid], ref_vals[valid], rtol=rtol, atol=atol,
        )


# --------------------------------------------------------------------------- #
#  Golden-file comparison: every measure from cal_measures                    #
# --------------------------------------------------------------------------- #
@pytest.mark.parametrize('measure_name', ALL_MEASURE_NAMES)
def test_measure_against_reference(ctx, measure_name):
    """Compare a single measure computed via cal_measures against the
    pre-generated reference NC file."""
    ref = ctx['ref']
    measures = ctx['measures']

    assert measure_name in measures.data_vars, \
        f'{measure_name} missing from cal_measures output'
    assert measure_name in ref.data_vars, \
        f'{measure_name} missing from reference NC'

    _assert_close(measures[measure_name].values, ref[measure_name].values)


# --------------------------------------------------------------------------- #
#  Physical-constraint checks (sanity, not golden-file)                       #
# --------------------------------------------------------------------------- #
def test_physical_constraints(ctx):
    """Verify key physical properties for a subset of measures."""
    m = ctx['measures']

    # relative dispersion > 0
    for name in ['r2_t', 'r2_r']:
        v = m[name].values
        v = v[np.isfinite(v)]
        assert (v > 0).all(), f'{name} has non-positive values'

    # structure functions >= 0
    for name in ['S2_t', 'S2_r']:
        v = m[name].values
        v = v[np.isfinite(v)]
        assert (v >= 0).all(), f'{name} has negative values'

    # kurtosis >= 1  (Cauchy-Schwarz:  <r^4>/<r^2>^2 >= 1)
    for name in ['ku_t']:
        v = m[name].values
        v = v[np.isfinite(v)]
        assert (v >= 1.0).all(), f'{name} < 1'

    # anisotropy >= 1  (ra >= rb  =>  sqrt(ra/rb) >= 1)
    for name in ['aniso_t', 'aniso_r']:
        v = m[name].values
        v = v[np.isfinite(v)]
        assert (v >= 1.0).all(), f'{name} < 1'

    # Lagrangian correlations in [-1, 1]
    for name in ['LVC_t', 'LVC_r', 'LAC_t', 'LAC_r']:
        v = m[name].values
        v = v[np.isfinite(v)]
        assert (v >= -1.01).all() and (v <= 1.01).all(), f'{name} out of [-1, 1]'


