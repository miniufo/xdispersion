# --------------------------------------------------------------------------- #
#  PDF & CDF (not included in cal_measures)                                   #
# --------------------------------------------------------------------------- #
def test_pdf_and_cdf(ctx):
    """Test probability_density_function and cumulative_density_function."""
    rd, pairs = ctx['rd'], ctx['pairs']
    _, _, _, r, _ = rd.separation_measures(pairs)

    # PDF
    PDF = probability_density_function(r, rbins=rbins)
    assert PDF.name == 'PDF'
    assert 'rbin' in PDF.dims
    valid = PDF.values[~np.isnan(PDF.values)]
    assert (valid >= 0).all()

    # CDF (auto bin-width)
    CDF = cumulative_density_function(PDF)
    assert CDF.name == 'CDF'
    assert 'rbin' in CDF.dims
    # CDF should be non-decreasing along rbin (not across rtime)
    diffs = CDF.diff('rbin')
    valid = np.isfinite(diffs.values)
    if valid.any():
        assert (diffs.values[valid] >= -1e-6).all(), 'CDF is decreasing along rbin'

    # CDF with explicit bin_edges
    CDF2 = cumulative_density_function(PDF, bin_edges=rbins.values)
    assert CDF2.name == 'CDF'


# --------------------------------------------------------------------------- #
#  Helper: principle_axis_components                                          #
# --------------------------------------------------------------------------- #
def test_principle_axis_components(ctx):
    """Test principle_axis_components helper."""
    rd, pairs = ctx['rd'], ctx['pairs']
    rx, ry, rxy, _, _ = rd.separation_measures(pairs)

    rx2m = (rx ** 2).mean('pair')
    ry2m = (ry ** 2).mean('pair')
    rxym = rxy.mean('pair')

    ra2, rb2, ang = principle_axis_components(rx2m, ry2m, rxym)

    # ra2 >= rb2  (major >= minor)
    valid = ~np.isnan(ra2.values)
    assert (ra2.values[valid] >= rb2.values[valid] - 1e-6).all()

    # trace preserved:  ra2 + rb2 == rx2m + ry2m
    np.testing.assert_allclose(
        ra2.values[valid] + rb2.values[valid],
        (rx2m + ry2m).values[valid], rtol=1e-4,
    )


# --------------------------------------------------------------------------- #
#  Helper: rotational_divergent_components                                     #
# --------------------------------------------------------------------------- #
def test_rotational_divergent_components(ctx):
    """Test rotational_divergent_components helper and compare against
    the S2rr_r / S2dd_r values in the reference NC."""
    rd, pairs = ctx['rd'], ctx['pairs']
    ref = ctx['ref']

    _, _, _, r, _ = rd.separation_measures(pairs)
    _, _, dul, dut, _, _, _ = rd.velocity_measures(pairs)

    S2ll = velocity_structure_function(dul, r, rbins=rbins, mean_at='const-r')
    S2tr = velocity_structure_function(dut, r, rbins=rbins, mean_at='const-r')

    S2rr, S2dd = rotational_divergent_components(S2ll, S2tr)
    assert S2rr.name == 'S2rr'
    assert S2dd.name == 'S2dd'
    assert 'rbin' in S2rr.dims

    # Compare against reference (align coordinates — rbin may differ
    # because rotational_divergent_components uses diff which shifts coords)
    for test_da, ref_name in [(S2rr, 'S2rr_r'), (S2dd, 'S2dd_r')]:
        ref_da = ref[ref_name]
        common = np.intersect1d(test_da.rbin.values, ref_da.rbin.values)
        if len(common) > 0:
            _assert_close(
                test_da.sel(rbin=common).values,
                ref_da.sel(rbin=common).values,
            )

    # trace preserved: S2rr + S2dd == S2ll + S2tr (where both finite)
    # Note: S2rr/S2dd may have fewer rbin coords than S2ll/S2tr due to
    # diff() inside rotational_divergent_components; align with inner join.
    total_rd = S2rr + S2dd
    total_lt = S2ll + S2tr
    aligned_rd, aligned_lt = xr.align(total_rd, total_lt, join='inner')
    valid = np.isfinite(aligned_rd.values) & np.isfinite(aligned_lt.values)
    if valid.any():
        np.testing.assert_allclose(
            aligned_rd.values[valid], aligned_lt.values[valid], rtol=1e-4,
        )


# --------------------------------------------------------------------------- #
#  Individual function: output naming verification                             #
#  (ensures each function returns the expected DataArray name)                #
# --------------------------------------------------------------------------- #
def test_output_naming(ctx):
    """Verify that each measure function returns the expected name."""
    rd, pairs = ctx['rd'], ctx['pairs']
    rx, ry, rxy, r, rpb = rd.separation_measures(pairs)
    du, dv, dul, dut, vmi, vmj, uv = rd.velocity_measures(pairs)
    dax, day, _, _, ai, aj, axy = rd.acceleration_measures(pairs)

    assert relative_dispersion(r, order=2, mean_at='const-t').name == 'r2_t'
    assert relative_dispersion(r, order=2, mean_at='const-r',
                               rbins=rbins).name == 'r2_r'
    assert velocity_structure_function(np.hypot(du, dv), r,
                                       mean_at='const-t').name == 'S2_t'
    assert velocity_structure_function(np.hypot(du, dv), r, rbins=rbins,
                                       mean_at='const-r').name == 'S2_r'
    assert relative_diffusivity(r, mean_at='const-t').name == 'K2_t'
    assert relative_diffusivity(r, mean_at='const-r',
                                rbins=rbins).name == 'K2_r'
    assert finite_amplitude_growth_rate(r, mean_at='const-t',
                                        samples='all').name == 'FAGRa_t'
    assert finite_amplitude_growth_rate(r, mean_at='const-t',
                                        samples='positive').name == 'FAGRp_t'
    assert initial_memory(rx, ry, du, dv, r,
                          mean_at='const-t').name == 'initm_t'
    assert anisotropy(rx, ry, rxy, r, mean_at='const-t').name == 'aniso_t'
    assert lagrangian_velocity_correlation(uv, vmi, vmj, r,
                                           mean_at='const-t').name == 'lvc_t'
    assert kurtosis(r, mean_at='const-t').name == 'Ku_t'
    assert cencini_vulpiani_exponent(r, mean_at='const-t').name == 'CVE_t'
    assert finite_size_lyapunov_exponent(r, rbins=rbins,
                                         mean_at='const-r').name == 'FSLE_r'
    assert cumulative_inverse_separation_time(r, rbins=rbins,
                                              mean_at='const-r').name == 'CIST_r'
